def text_to_matrix(text: str, cols: int = 52, rows: int = 7, intensity: int = 3) -> list:
    """
    Renders input text horizontally centered on a rows x cols matrix.
    """
    text = text.upper()
    rendered = [FONT_MATRIX.get(ch, FONT_MATRIX[' ']) for ch in text]
    total_w = sum(len(g[0]) + 1 for g in rendered) - (1 if rendered else 0)

    matrix = [[0 for _ in range(cols)] for _ in range(rows)]
    cursor = max(0, (cols - total_w) // 2)

    for glyph in rendered:
        glyph_w = len(glyph[0])
        for r in range(min(rows, len(glyph))):
            for c in range(glyph_w):
                target_col = cursor + c
                if 0 <= target_col < cols and glyph[r][c] != ' ':
                    matrix[r][target_col] = intensity
        cursor += glyph_w + 1
        if cursor >= cols:
            break

    return matrix
